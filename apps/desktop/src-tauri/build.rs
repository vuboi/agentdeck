use std::{env, fs, path::PathBuf};

/// The commands of `tauri::generate_handler![...]` in `src/lib.rs`, by name (the last segment of each path).
fn handler_commands() -> Vec<String> {
    let source = fs::read_to_string("src/lib.rs").unwrap_or_default();
    let Some(start) = source.find("generate_handler![") else {
        return Vec::new();
    };
    let rest = &source[start + "generate_handler![".len()..];
    let Some(end) = rest.find(']') else {
        return Vec::new();
    };
    rest[..end]
        .lines()
        .map(|line| line.split("//").next().unwrap_or_default())
        .flat_map(|line| line.split(','))
        .map(|item| {
            item.trim()
                .rsplit("::")
                .next()
                .unwrap_or_default()
                .to_string()
        })
        .filter(|name| {
            !name.is_empty() && name.chars().all(|c| c.is_ascii_alphanumeric() || c == '_')
        })
        .collect()
}

/// The capability of the Preview's own copy of the app (see `inTauri` in the frontend). In a debug build the app
/// commands are listed, so that copy, at the dev address only, can use them with real data; a release build has none of
/// this and the capability grants nothing.
fn preview_capability(commands: &[String]) -> String {
    if commands.is_empty() {
        return r#"{ "identifier": "debug-preview", "description": "Nothing in a release build.", "windows": ["main"], "permissions": [] }"#.to_string();
    }
    let permissions = commands
        .iter()
        .map(|name| format!("\"allow-{}\"", name.replace('_', "-")))
        .chain(std::iter::once("\"core:default\"".to_string()))
        .collect::<Vec<_>>()
        .join(", ");
    format!(
        r#"{{ "identifier": "debug-preview", "description": "Debug builds only (generated by build.rs): the app commands for the main window and for the Preview's webviews at the dev address.", "local": true, "windows": ["main"], "webviews": ["browser-*"], "remote": {{ "urls": ["http://127.0.0.1:1420/*"] }}, "permissions": [{permissions}] }}"#
    )
}

/// Grants the main window the app commands registered by `generate_handler!` in every build profile.
fn default_capability(commands: &[String]) -> Result<String, String> {
    let source = fs::read_to_string("capabilities/default.json")
        .map_err(|error| format!("could not read the default capability: {error}"))?;
    let mut capability: serde_json::Value = serde_json::from_str(&source)
        .map_err(|error| format!("could not parse the default capability: {error}"))?;
    let permissions = capability
        .get_mut("permissions")
        .and_then(serde_json::Value::as_array_mut)
        .ok_or("the default capability has no permissions array")?;

    for command in commands {
        let permission = format!("allow-{}", command.replace('_', "-"));
        if !permissions
            .iter()
            .any(|entry| entry.as_str() == Some(&permission))
        {
            permissions.push(serde_json::Value::String(permission));
        }
    }

    serde_json::to_string_pretty(&capability)
        .map_err(|error| format!("could not serialize the default capability: {error}"))
}

fn main() {
    // The Windows taskbar icon is embedded in the executable. Make Cargo rebuild when it changes.
    println!("cargo:rerun-if-changed=icons/icon.ico");
    println!("cargo:rerun-if-changed=src/lib.rs");
    println!("cargo:rerun-if-changed=capabilities/default.json");

    let debug = env::var("PROFILE").is_ok_and(|profile| profile == "debug");
    let commands = handler_commands();
    let preview_commands = if debug { commands.as_slice() } else { &[] };
    // A handler list that was not read would lock the app out: stop instead.
    if commands.len() < 10 {
        eprintln!("build.rs: could not read the command list of generate_handler! in src/lib.rs");
        std::process::exit(1);
    }

    // The capabilities are collected in the build folder: the committed default one as it is, and the Preview's.
    let out =
        PathBuf::from(env::var("OUT_DIR").unwrap_or_else(|_| ".".into())).join("capabilities");
    let written = fs::create_dir_all(&out)
        .and_then(|()| {
            default_capability(&commands)
                .map_err(std::io::Error::other)
                .and_then(|capability| fs::write(out.join("default.json"), capability))
        })
        .and_then(|()| {
            fs::write(
                out.join("debug-preview.json"),
                preview_capability(preview_commands),
            )
        });
    if let Err(error) = written {
        eprintln!("build.rs: could not write the capabilities: {error}");
        std::process::exit(1);
    }
    let pattern: &'static str = Box::leak(
        format!("{}/*.json", out.display().to_string().replace('\\', "/")).into_boxed_str(),
    );

    let mut attributes = tauri_build::Attributes::new().capabilities_path_pattern(pattern);
    let names: Vec<&'static str> = commands
        .into_iter()
        .map(|name| &*Box::leak(name.into_boxed_str()))
        .collect();
    let names: &'static [&'static str] = Box::leak(names.into_boxed_slice());
    attributes = attributes.app_manifest(tauri_build::AppManifest::new().commands(names));
    if let Err(error) = tauri_build::try_build(attributes) {
        eprintln!("build.rs: {error}");
        std::process::exit(1);
    }
}
