// Bundles every lucide icon the app names, so the packaged app draws them offline (z-ui-svelte otherwise fetches
// each one from a CDN, which the app's CSP blocks: the icons show as "?"). Run after using a new lucide icon:
//   pnpm gen:icons
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { join } from 'node:path';
import { pathToFileURL } from 'node:url';

const src = 'apps/desktop/src';
const names = new Set();
const walk = (dir) => {
  for (const entry of readdirSync(dir)) {
    const path = join(dir, entry);
    if (statSync(path).isDirectory()) walk(path);
    else if (/\.(svelte|ts)$/.test(entry) && !path.endsWith('bundled-icons.ts')) {
      for (const match of readFileSync(path, 'utf8').matchAll(/\blucide[A-Z][A-Za-z0-9]*/g)) names.add(match[0]);
    }
  }
};
walk(src);

const require = createRequire(join(process.cwd(), 'apps/desktop/package.json'));
const available = await import(pathToFileURL(require.resolve('@ng-icons/lucide')).href);
const found = [...names].filter((name) => name in available).sort();
const missing = [...names].filter((name) => !(name in available));

const lines = [
  '// Generated by scripts/gen-icons.mjs: the lucide icons the app uses, bundled so they never wait on a CDN.',
  "import { zProvideIcons } from '@shival99/z-ui-svelte';",
  'import {',
  ...found.map((name) => `  ${name},`),
  "} from '@ng-icons/lucide';",
  '',
  'zProvideIcons({',
  ...found.map((name) => `  ${name},`),
  '});',
  '',
];
writeFileSync(join(src, 'lib/bundled-icons.ts'), lines.join('\n'));
console.log(`${found.length} icons bundled${missing.length ? `; not in @ng-icons/lucide (stay on the CDN): ${missing.join(', ')}` : ''}`);
